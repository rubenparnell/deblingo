create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique check (username is null or username ~ '^[A-Za-z0-9_]{3,30}$'),
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.board_options (
  id bigint generated by default as identity primary key,
  label text not null check (char_length(trim(label)) between 1 and 120),
  difficulty text not null default 'common'
    check (difficulty in ('free', 'common', 'rare')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.board_settings (
  id integer primary key check (id = 1),
  free_count integer not null default 1 check (free_count >= 0),
  common_count integer not null default 15 check (common_count >= 0),
  rare_count integer not null default 9 check (rare_count >= 0),
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  check (free_count + common_count + rare_count = 25)
);

create table public.lectures (
  id bigint generated by default as identity primary key,
  source_uid text not null unique,
  title text not null,
  starts_at timestamptz not null,
  ends_at timestamptz,
  uploaded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.lecture_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  source_uid text not null,
  title text not null,
  starts_at timestamptz not null,
  ends_at timestamptz,
  board jsonb not null,
  marked_ids bigint[] not null default '{}',
  score integer not null default 0 check (score >= 0),
  completed_lines integer not null default 0 check (completed_lines between 0 and 12),
  updated_at timestamptz not null default now(),
  unique (user_id, source_uid)
);

create or replace function public.get_lecture_leaderboard()
returns table (
  source_uid text,
  title text,
  starts_at timestamptz,
  username text,
  completed_lines integer,
  marked_squares integer
)
language sql
security definer
set search_path = ''
stable
as $$
  select
    history.source_uid,
    history.title,
    history.starts_at,
    profile.username,
    history.completed_lines,
    history.score
  from public.lecture_history as history
  join public.profiles as profile on profile.id = history.user_id
  where profile.username is not null;
$$;

revoke all on function public.get_lecture_leaderboard() from public;
grant execute on function public.get_lecture_leaderboard() to anon, authenticated;

create or replace function public.set_lecture_history_completed_lines()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
declare
  line_number integer;
  line_position integer;
  board_index integer;
  option_id bigint;
  line_complete boolean;
  completed_count integer := 0;
begin
  for line_number in 0..11 loop
    line_complete := true;
    for line_position in 0..4 loop
      if line_number < 5 then
        board_index := line_number * 5 + line_position;
      elsif line_number < 10 then
        board_index := line_position * 5 + line_number - 5;
      elsif line_number = 10 then
        board_index := line_position * 6;
      else
        board_index := (line_position + 1) * 4;
      end if;

      option_id := (new.board -> board_index ->> 'id')::bigint;
      if option_id is null or not (option_id = any(new.marked_ids)) then
        line_complete := false;
        exit;
      end if;
    end loop;
    if line_complete then
      completed_count := completed_count + 1;
    end if;
  end loop;

  new.completed_lines := completed_count;
  return new;
end;
$$;

create trigger set_lecture_history_completed_lines
  before insert or update of board, marked_ids
  on public.lecture_history
  for each row
  execute function public.set_lecture_history_completed_lines();

