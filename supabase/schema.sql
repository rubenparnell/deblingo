create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique check (username is null or username ~ '^[A-Za-z0-9_]{3,30}$'),
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.board_options (
  id bigint generated by default as identity primary key,
  label text not null check (char_length(trim(label)) between 1 and 120),
  category text not null default 'General' check (char_length(trim(category)) between 1 and 40),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.board_options enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and is_admin = true
  );
$$;

create policy "Anyone can read board options"
  on public.board_options for select
  using (true);

create policy "Admins can add board options"
  on public.board_options for insert
  to authenticated
  with check (public.is_admin() and created_by = (select auth.uid()));

create policy "Admins can delete board options"
  on public.board_options for delete
  to authenticated
  using (public.is_admin());

create policy "Users can read their own profile"
  on public.profiles for select
  to authenticated
  using (id = (select auth.uid()));

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, username)
  values (new.id, lower(new.raw_user_meta_data ->> 'username'));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.get_email_for_username(login_username text)
returns text
language sql
security definer
set search_path = public, auth
stable
as $$
  select u.email
  from auth.users as u
  join public.profiles as p on p.id = u.id
  where lower(p.username) = lower(trim(login_username))
  limit 1;
$$;

grant execute on function public.get_email_for_username(text) to anon, authenticated;

create or replace function public.set_my_username(new_username text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'You must be signed in';
  end if;

  if lower(trim(new_username)) !~ '^[a-z0-9_]{3,30}$' then
    raise exception 'Username must be 3-30 characters using letters, numbers, or underscores';
  end if;

  insert into public.profiles (id, username)
  values (auth.uid(), lower(trim(new_username)))
  on conflict (id) do update
    set username = excluded.username;
end;
$$;

grant execute on function public.set_my_username(text) to authenticated;

