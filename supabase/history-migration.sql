create table public.lecture_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  source_uid text not null,
  title text not null,
  starts_at timestamptz not null,
  ends_at timestamptz,
  board jsonb not null,
  marked_ids bigint[] not null default '{}',
  score integer not null default 0 check (score >= 0),
  updated_at timestamptz not null default now(),
  unique (user_id, source_uid)
);

alter table public.lecture_history enable row level security;

create policy "Users can read their own lecture history"
  on public.lecture_history for select
  to authenticated
  using (user_id = (select auth.uid()));

create policy "Users can add their own lecture history"
  on public.lecture_history for insert
  to authenticated
  with check (user_id = (select auth.uid()));

create policy "Users can update their own lecture history"
  on public.lecture_history for update
  to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
