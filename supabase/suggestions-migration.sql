create table public.board_suggestions (
  id bigint generated by default as identity primary key,
  label text not null check (char_length(trim(label)) between 1 and 120),
  suggested_by uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'rejected')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.board_suggestions enable row level security;

create policy "Users can submit board suggestions"
  on public.board_suggestions for insert
  to authenticated
  with check (suggested_by = (select auth.uid()));

create policy "Users can read their own board suggestions"
  on public.board_suggestions for select
  to authenticated
  using (suggested_by = (select auth.uid()) or public.is_admin());

create policy "Admins can review board suggestions"
  on public.board_suggestions for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());
